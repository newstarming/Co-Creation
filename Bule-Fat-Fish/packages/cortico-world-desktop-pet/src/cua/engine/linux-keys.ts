/**
 * Windows virtual-key codes (what `keys.ts` parses) to X11 keysyms, and the exit code of a zenity
 * question. Pure, so it is tested on every platform.
 */

const KEYSYMS: Record<number, number> = {
  0x10: 0xffe1, 0x11: 0xffe3, 0x12: 0xffe9, 0x5b: 0xffeb, // Shift_L, Control_L, Alt_L, Super_L
  0x0d: 0xff0d, 0x1b: 0xff1b, 0x09: 0xff09, 0x20: 0x0020, 0x08: 0xff08, 0x2e: 0xffff, 0x2d: 0xff63,
  0x24: 0xff50, 0x23: 0xff57, 0x21: 0xff55, 0x22: 0xff56, 0x25: 0xff51, 0x26: 0xff52, 0x27: 0xff53, 0x28: 0xff54,
  0x14: 0xffe5, 0x2c: 0xff61, 0x5d: 0xff67,
  // XF86AudioRaiseVolume, LowerVolume, Mute, Play
  0xaf: 0x1008ff13, 0xae: 0x1008ff11, 0xad: 0x1008ff12, 0xb3: 0x1008ff14,
  // US-layout punctuation: ; = , - . / ` [ \ ] '
  0xba: 0x3b, 0xbb: 0x3d, 0xbc: 0x2c, 0xbd: 0x2d, 0xbe: 0x2e, 0xbf: 0x2f, 0xc0: 0x60, 0xdb: 0x5b, 0xdc: 0x5c, 0xdd: 0x5d, 0xde: 0x27,
};

/** The keysym for a Windows virtual-key code, or null for a key X11 has no name for. */
export function linuxKeysym(vk: number): number | null {
  if (KEYSYMS[vk] !== undefined) return KEYSYMS[vk]!;
  if (vk >= 0x41 && vk <= 0x5a) return vk + 0x20; // a–z
  if (vk >= 0x30 && vk <= 0x39) return vk; // 0–9
  if (vk >= 0x70 && vk <= 0x87) return 0xffbe + (vk - 0x70); // F1–F24
  return null;
}

/** What `zenity --question --timeout` exited with: 0 for the yes button, 5 when time ran out, anything else no. */
export function zenityAnswer(code: number | null): 'yes' | 'no' | 'timeout' {
  return code === 0 ? 'yes' : code === 5 ? 'timeout' : 'no';
}
